import React from 'react';
import { computeDiff } from '@/lib/diff';
import { parseInternalLinkSuggestions } from '@/lib/internal-link-fix';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Textarea } from '@/components/ui/textarea';
import { CopyButton } from '@/components/copy-button';
import { OUTCOME_LABEL, OUTCOME_VARIANT, RISK_TIER_LABEL, RISK_TIER_VARIANT, CHECK_ICON, CHECK_LABEL } from '@/lib/guard-outcome-ui';
import type { ProofCheckResult } from '@/lib/proof-layer';
import type { ReceiptView } from '@/lib/proof-receipt';
import { ProofReceipt } from './proof-receipt';
import { computeChangeLifecycle } from '@/lib/change-lifecycle';
import { ChangeLifecycle } from '@/components/dashboard/change-lifecycle';
import { cn } from '@/lib/utils';
import type { Action, GuardResult, ProofOutcome, RiskTier } from '@prisma/client';

export interface ActionDetailData
  extends Pick<
    Action,
    | 'id'
    | 'actionType'
    | 'pageUrl'
    | 'currentValue'
    | 'draftContent'
    | 'status'
    | 'riskTier'
    | 'generationStatus'
    | 'generationError'
    | 'createdAt'
    | 'decidedAt'
    | 'outcomeMeasuredAt'
  > {
  guardResult: Pick<GuardResult, 'outcome' | 'reasoning' | 'checksRun'> | null;
}

// Per-actionType copy. meta_description is the historical default/fallback (every Action row
// created before Phase 1F is that type, and an unrecognized future actionType should degrade to
// its behavior rather than render nothing). Real distinctions Phase 1F introduced: canonical_fix
// is deterministic code, not an AI model, so it gets its own honest disclosure line; it has no
// SERP-preview meaning (it's a <head> tag, not a snippet Google displays) and a different apply
// destination (page markup, not a CMS meta-description field).
const ACTION_TYPE_COPY: Record<
  string,
  {
    heading: string;
    // Dashboard audit, plain-language labels: a layperson-readable phrase leading the detail
    // page, with `heading` (the existing technical term, also what badges/filters use) kept
    // small underneath it instead of being the only thing shown.
    plainSummary: string;
    disclosureText: string;
    applyInstructions: string;
    showSerpPreview: boolean;
  }
> = {
  meta_description: {
    heading: 'Meta description change',
    plainSummary: 'Change what shows up in Google search results',
    disclosureText: 'This description was drafted by AI.',
    applyInstructions: "Copy this into your site's meta description field. Dex does not change your website.",
    showSerpPreview: true,
  },
  canonical_fix: {
    heading: 'Canonical tag fix',
    plainSummary: 'Tell Google which page is the main one',
    disclosureText: 'This fix was generated by deterministic code, not an AI model.',
    applyInstructions: 'Copy this into the <head> section of the page, replacing any existing canonical tag. Dex does not change your website.',
    showSerpPreview: false,
  },
  structured_data_fix: {
    heading: 'Structured data fix',
    plainSummary: 'Help search engines understand this page',
    disclosureText: 'This fix was generated by deterministic code, not an AI model.',
    applyInstructions: 'Copy this into the <head> section of the page. Dex does not change your website.',
    showSerpPreview: false,
  },
  entity_markup_fix: {
    heading: 'Entity markup fix',
    plainSummary: 'Help search engines know who you are',
    disclosureText: 'This fix was generated by deterministic code, not an AI model.',
    applyInstructions: 'Copy this into the <head> section of your homepage. Dex does not change your website.',
    showSerpPreview: false,
  },
  restricted_wording_fix: {
    heading: 'Restricted wording fix',
    plainSummary: 'Remove wording that could get your account flagged',
    disclosureText: 'This rewrite was drafted by AI.',
    applyInstructions: 'Copy this into the page, replacing the flagged text. Dex does not change your website.',
    showSerpPreview: false,
  },
  internal_link_fix: {
    heading: 'Internal link suggestion',
    plainSummary: 'Add a link to this page from other pages on your site',
    disclosureText: 'This suggestion was drafted by AI using pages this scan found on your site.',
    applyInstructions: 'Each line names another page on your site and suggested anchor text. Add that link from that page to this one. Dex does not change your website.',
    showSerpPreview: false,
  },
};

// Review queue list badge label, per actionType. Derived from ACTION_TYPE_COPY's own heading
// text rather than a second, hand-maintained string table — the list row and the detail page
// then can't drift out of sync with each other. Same fallback as ActionDetail below
// (meta_description) for an actionType this map hasn't seen yet.
export const ACTION_TYPE_LABEL: Record<string, string> = Object.fromEntries(
  Object.entries(ACTION_TYPE_COPY).map(([actionType, copy]) => [actionType, copy.heading])
);

// Lives here, not in review-queue-list.tsx: that module is 'use client', so the /review server
// page (via review-queue-filter.ts) can't call functions exported from it.
export function actionTypeLabel(actionType: string): string {
  return ACTION_TYPE_LABEL[actionType] ?? actionType;
}

// Item 2 (overseer production check, 2026-10-16): same plain-language-first pattern as this
// file's own detail page -- a layperson sentence leading, actionTypeLabel's existing term kept
// small underneath. Falls back to actionTypeLabel itself (not the raw actionType) so a type
// with no plainSummary yet still reads as a phrase, not an enum value.
export function actionTypePlainSummary(actionType: string): string {
  return ACTION_TYPE_COPY[actionType]?.plainSummary ?? actionTypeLabel(actionType);
}

export function ActionDetail({ action, revision, receipt }: { action: ActionDetailData; revision: string; receipt?: ReceiptView }) {
  const copy = ACTION_TYPE_COPY[action.actionType] ?? ACTION_TYPE_COPY.meta_description;
  const checksRun = (Array.isArray(action.guardResult?.checksRun) ? action.guardResult.checksRun : []) as unknown as ProofCheckResult[];
  const isFinal = action.status === 'approved' || action.status === 'edited';
  const generationFailed = action.generationStatus === 'failed';
  const canApprove = action.status === 'pending' && action.generationStatus === 'succeeded' && !!action.draftContent.trim() &&
    action.guardResult != null && action.guardResult.outcome !== 'block' &&
    Array.isArray(action.guardResult.checksRun) && action.guardResult.checksRun.length > 0;
  // Dashboard audit: this draftContent format is stored as "URL | anchor text" lines (see
  // internal-link-fix.ts) -- rendered as a real link list instead of the raw diff/text below,
  // which showed it as "url | label url | label" on one line. Empty when the model's own
  // "nothing is relevant" plain sentence was drafted, or on any unparseable line -- the diff
  // view below still renders that honestly as plain text.
  const internalLinkSuggestions = action.actionType === 'internal_link_fix'
    ? parseInternalLinkSuggestions(action.draftContent)
    : [];
  const lifecycleStages = computeChangeLifecycle({
    createdAt: action.createdAt,
    generationStatus: action.generationStatus,
    guardResult: action.guardResult,
    status: action.status,
    decidedAt: action.decidedAt,
    outcomeMeasuredAt: action.outcomeMeasuredAt,
  });

  return (
    <>
      <p className="break-all text-sm text-muted-foreground">{action.pageUrl}</p>
      <h1 className="mt-1 text-2xl font-semibold text-foreground tracking-tight">{copy.plainSummary}</h1>
      <p className="text-xs text-muted-foreground">{copy.heading}</p>

      <div className="mt-3">
        <ChangeLifecycle stages={lifecycleStages} />
      </div>

      {generationFailed ? (
        <div className="mt-4 flex flex-col gap-3 rounded-md border border-destructive/40 bg-destructive/10 px-4 py-3 text-sm">
          <p className="text-foreground">
            Dex found this page needs a change, but couldn&apos;t draft one
            {action.generationError ? `: ${action.generationError}` : '.'}
          </p>
          <form action={`/api/actions/${action.id}/retry-draft`} method="post">
            <Button type="submit" size="sm">
              Retry draft
            </Button>
          </form>
        </div>
      ) : (
        <p className="mt-4 rounded-md border border-border bg-muted px-4 py-3 text-sm text-foreground">{copy.disclosureText}</p>
      )}

      {/* SERP preview — real URL + real drafted description only. No page title exists in
          Action data, so none is invented; Google's own real behavior (may show a different
          title/description, may truncate) is stated honestly rather than simulated exactly.
          Only meaningful for a Google-snippet actionType (meta_description) — a markup fix like
          canonical_fix isn't something Google displays, so showing a fake "preview" of it would
          be dishonest, not just redundant. */}
      {!generationFailed && copy.showSerpPreview && (
        <Card className="mt-6">
          <CardHeader>
            <CardTitle className="text-sm font-medium text-muted-foreground">Google preview</CardTitle>
          </CardHeader>
          <CardContent>
            <p className="truncate text-xs text-[var(--dex-app-success)]">{action.pageUrl}</p>
            <p className="mt-1 text-sm text-foreground">{action.draftContent}</p>
            <p className="mt-2 text-xs text-muted-foreground">
              Google may show a different title or description and could truncate this content
              {action.draftContent.length > 155 ? ` (this draft is ${action.draftContent.length} characters).` : '.'}
            </p>
          </CardContent>
        </Card>
      )}

      {!generationFailed && (
      <Card className="mt-6">
        <CardHeader>
          <CardTitle className="text-sm font-medium text-muted-foreground">What changes</CardTitle>
        </CardHeader>
        <CardContent
          className="text-sm leading-relaxed"
          role="region"
          aria-label={internalLinkSuggestions.length > 0 ? 'Suggested internal links' : 'Diff between current and drafted content'}
        >
          {internalLinkSuggestions.length > 0 ? (
            <ul className="flex flex-col gap-2">
              {internalLinkSuggestions.map((suggestion, index) => (
                <li key={index}>
                  <a
                    href={suggestion.url}
                    title={suggestion.url}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="font-medium text-accent underline-offset-4 hover:underline"
                  >
                    {suggestion.anchorText}
                  </a>
                  <span className="ml-2 break-all text-xs text-muted-foreground">{suggestion.url}</span>
                </li>
              ))}
            </ul>
          ) : (
          computeDiff(action.currentValue ?? '', action.draftContent).map((segment, index) => {
            if (segment.type === 'equal') return <span key={index}>{segment.value}</span>;
            if (segment.type === 'added') {
              return (
                <ins
                  key={index}
                  className="rounded-sm px-0.5 no-underline"
                  style={{ backgroundColor: 'var(--dex-app-success-bg)', color: 'var(--dex-app-success)' }}
                >
                  {segment.value}
                </ins>
              );
            }
            return (
              <del
                key={index}
                className="rounded-sm px-0.5"
                style={{ backgroundColor: 'var(--dex-app-danger-bg)', color: 'var(--dex-app-danger)' }}
              >
                {segment.value}
              </del>
            );
          })
          )}
        </CardContent>
      </Card>
      )}

      {action.guardResult && (
        <Card className="mt-6">
          <CardHeader className="flex flex-row items-center justify-between space-y-0">
            <CardTitle className="flex flex-col gap-0.5 text-sm font-medium">
              <span>Automatic safety check</span>
              <span className="text-xs font-normal text-muted-foreground">Five safety checks</span>
            </CardTitle>
            <div className="flex items-center gap-2">
              <Badge variant={RISK_TIER_VARIANT[action.riskTier as RiskTier] ?? 'secondary'}>
                {RISK_TIER_LABEL[action.riskTier as RiskTier] ?? action.riskTier}
              </Badge>
              <Badge variant={OUTCOME_VARIANT[action.guardResult.outcome as ProofOutcome] ?? 'secondary'}>
                {action.guardResult.outcome === 'pass'
                  ? 'Checks passed'
                  : (OUTCOME_LABEL[action.guardResult.outcome as ProofOutcome] ?? action.guardResult.outcome)}
              </Badge>
            </div>
          </CardHeader>
          <CardContent>
            <p className="mb-3 text-sm text-muted-foreground">Dex can&apos;t show exactly which version of the text these checks ran on.</p>
            {action.status === 'edited' && (
              <p className="mb-3 text-sm text-muted-foreground">
                Your edited version was not rechecked.
              </p>
            )}
            <p className="text-sm text-muted-foreground">{action.guardResult.reasoning}</p>

            <div className="mt-4 flex gap-2">
              {checksRun.map((check, index) => {
                const Icon = CHECK_ICON[check.check];
                if (!Icon) return null;
                const label = `${CHECK_LABEL[check.check] ?? check.check}: ${check.result === 'pass' ? 'passed' : 'failed'}`;
                return (
                  <span
                    key={`${check.check}-${index}`}
                    role="img"
                    aria-label={label}
                    title={label}
                    className={cn(
                      'flex h-8 w-8 items-center justify-center rounded-md border',
                      check.result === 'pass'
                        ? 'border-border text-muted-foreground'
                        : action.guardResult?.outcome === 'block'
                          ? 'border-[var(--dex-app-danger)] text-[var(--dex-app-danger)] bg-[var(--dex-app-danger-bg)]'
                          : 'border-[var(--dex-app-warning)] text-[var(--dex-app-warning)] bg-[var(--dex-app-warning-bg)]'
                    )}
                  >
                    <Icon size={16} weight="regular" aria-hidden="true" />
                  </span>
                );
              })}
            </div>

            <ul className="mt-4 flex flex-col gap-1.5 text-sm">
              {checksRun.map((check, index) => (
                <li key={`${check.check}-${index}`} className="flex items-start gap-2">
                  <span
                    className={
                      check.result === 'pass'
                        ? 'text-[var(--dex-app-success)]'
                        : action.guardResult?.outcome === 'block'
                          ? 'text-[var(--dex-app-danger)]'
                          : 'text-[var(--dex-app-warning)]'
                    }
                  >
                    {check.result === 'pass' ? '✓' : '!'}
                  </span>
                  <span className="text-foreground">
                    <span className="font-medium">{CHECK_LABEL[check.check] ?? check.check}:</span>{' '}
                    {check.detail}
                  </span>
                </li>
              ))}
            </ul>
          </CardContent>
        </Card>
      )}

      {action.status === 'pending' && (
        <div className="mt-6 flex flex-wrap items-center gap-3">
          {canApprove && (
            <form action={`/api/actions/${action.id}/approve`} method="post">
              <input type="hidden" name="expectedRevision" value={revision} />
              {/* "Approve" alone reads as ambiguous about what happens next — the directive is
                  explicit: this approves a draft for the existing workflow, it does not publish
                  or push to a live CMS (Dex has no publishing integration). */}
              <Button type="submit" className="h-11">
                Approve draft
              </Button>
            </form>
          )}
          <form action={`/api/actions/${action.id}/reject`} method="post">
            <input type="hidden" name="expectedRevision" value={revision} />
            <Button type="submit" variant="outline" className="h-11">
              Reject
            </Button>
          </form>
          {!generationFailed && (
          <details className="ml-auto w-full sm:w-auto">
            <summary className="inline-flex min-h-11 cursor-pointer items-center text-sm font-medium text-accent focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring">Edit before using</summary>
            <form action={`/api/actions/${action.id}/edit`} method="post" className="mt-3 flex flex-col gap-2">
              <input type="hidden" name="expectedRevision" value={revision} />
              <label htmlFor="draftContent" className="sr-only">
                Edited draft content
              </label>
              <p className="text-sm text-muted-foreground">Your edited version is not rechecked by the safety guard.</p>
              <Textarea id="draftContent" name="draftContent" defaultValue={action.draftContent} rows={3} />
              <Button type="submit" className="h-11 self-start">
                Save and use this version
              </Button>
            </form>
          </details>
          )}
        </div>
      )}

      {isFinal && (
        <Card className="mt-6">
          <CardHeader>
            <CardTitle className="text-sm font-medium">Ready to apply</CardTitle>
          </CardHeader>
          <CardContent>
            <p className="text-sm text-muted-foreground">{copy.applyInstructions}</p>
            <div className="mt-3 flex items-start gap-2 rounded-md border border-border bg-muted px-3 py-2">
              <code className="flex-1 text-sm text-foreground">{action.draftContent}</code>
              <CopyButton text={action.draftContent} />
            </div>
            <div className="mt-3 flex flex-wrap gap-3">
              <form action={`/api/actions/${action.id}/revert`} method="post">
                <input type="hidden" name="expectedRevision" value={revision} />
                <Button type="submit" variant="outline" size="sm">
                  Undo this decision
                </Button>
              </form>
              <Button asChild variant="outline" size="sm">
                <a href={`/api/actions/${action.id}/evidence`}>Download evidence pack</a>
              </Button>
            </div>
          </CardContent>
        </Card>
      )}

      {action.status === 'rejected' && (
        <div className="mt-6">
          <p className="text-sm text-muted-foreground">You rejected this draft. No changes were applied.</p>
          <form action={`/api/actions/${action.id}/revert`} method="post" className="mt-3">
            <input type="hidden" name="expectedRevision" value={revision} />
            <Button type="submit" variant="outline" size="sm">
              Undo this decision
            </Button>
          </form>
        </div>
      )}
      {receipt && <div className="mt-6"><ProofReceipt receipt={receipt} currentStatus={action.status} /></div>}
    </>
  );
}
